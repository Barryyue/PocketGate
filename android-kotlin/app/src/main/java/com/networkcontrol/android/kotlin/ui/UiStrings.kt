class UiStrings internal constructor(languageTag: String) {
    private val table: Map<S, String> = when {
        languageTag.startsWith("zh-TW", ignoreCase = true) ||
            languageTag.startsWith("zh-Hant", ignoreCase = true) -> TW
        languageTag.startsWith("zh", ignoreCase = true) -> CN
        else -> EN
    }

    operator fun get(key: S): String = table[key] ?: EN[key] ?: key.name

    fun format(key: S, vararg args: Any?): String = get(key).format(*args)
}

@Composable
fun rememberUiStrings(): UiStrings {
    val configuration = LocalConfiguration.current
    val tag = configuration.locales[0]?.toLanguageTag().orEmpty()
    return remember(tag) { UiStrings(tag) }
}

